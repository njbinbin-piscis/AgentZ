import { act, create, type ReactTestRenderer } from "react-test-renderer";
import { afterEach, expect, it, vi } from "vitest";
const state = vi.hoisted(() => ({ language: "en", ui: { scm: [], outputChannels: [{id: "log", label: "Log", content: ""}], debugOutput: [], running: false, treeViews: [], tests: [], webviews: [], activeOutput: "log" } }));
vi.mock("../../extensions/ui/useExtensionUi", () => ({ useExtensionUi: () => state.ui }));
vi.mock("react-i18next", () => ({ useTranslation: () => ({ t: (key: string) => `${state.language}:${key}` }) }));
vi.mock("./Terminal", () => ({ default: () => <div /> }));
vi.mock("../../components/DropdownSelect", () => ({ default: () => <div /> }));
vi.mock("../../extensions/extensionService", () => ({ extensionService: {} }));
vi.mock("../../extensions/extensionUiStore", () => ({ extensionUiStore: {} }));
vi.mock("../../extensions/ui/TreeView", () => ({ default: () => <div /> }));
vi.mock("../../extensions/ui/WebviewHost", () => ({ default: () => <div /> }));
vi.mock("../../extensions/ui/DebugView", () => ({ default: () => <div /> }));
import BottomPanel from "./BottomPanel";
let view: ReactTestRenderer | undefined;
afterEach(() => { act(() => view?.unmount()); view = undefined; state.language = "en"; });
it("real dock routes arrow focus and publishes matching selected/panel semantics in both languages", () => {
  const change = vi.fn(); const focused: string[] = [];
  const props = {projectDir: "A", open: true, activeTab: "terminal" as const, onTabChange: change, onClose: vi.fn(), height: 200};
  act(() => { view = create(<BottomPanel {...props} />, { createNodeMock: element => ({focus: () => focused.push(element.props.id)}) }); });
  let tabs = view!.root.findAll(n => n.props.role === "tab");
  expect(tabs.map(tab => tab.props.tabIndex)).toEqual([0, -1]);
  const prevent = vi.fn();
  act(() => tabs[0].props.onKeyDown({key: "ArrowLeft", preventDefault: prevent}));
  expect(change).toHaveBeenCalledWith("output"); expect(prevent).toHaveBeenCalledOnce();
  expect(focused[focused.length - 1]).toBe(tabs[1].props.id);
  state.language = "zh";
  act(() => view!.update(<BottomPanel {...props} activeTab="output" />));
  tabs = view!.root.findAll(n => n.props.role === "tab");
  expect(tabs.map(tab => tab.props["aria-selected"])).toEqual([false, true]);
  const panel = view!.root.findByProps({role: "tabpanel"});
  expect(panel.props["aria-labelledby"]).toBe(tabs[1].props.id);
  expect(tabs.every(tab => tab.props["aria-controls"] === panel.props.id)).toBe(true);
  expect(tabs[1].children.join("")).toContain("zh:");
  change.mockClear();
  tabs[1].props.onKeyDown({key: "ArrowRight", ctrlKey: true, preventDefault: prevent});
  expect(change).not.toHaveBeenCalled();
});
