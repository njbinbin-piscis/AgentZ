import { act, create, type ReactTestRenderer } from "react-test-renderer";
import { afterEach, describe, expect, it, vi } from "vitest";
import OnboardingModal from "../src/components/OnboardingModal";
import WorkzEmptyState from "../src/workspaces/workz/WorkzEmptyState";
import AgentFilePreview from "../src/workspaces/workz/AgentFilePreview";
import { EditorConflictTracker } from "../src/workspaces/codez/editorConflict";
import {
  consumeUserRecentEdits,
  formatUserRecentEditsBlock,
} from "../src/services/tauri/chat";

const tFn = (key: string) => key;
const translationHook = { t: tFn, i18n: { language: "zh" } };
vi.mock("react-i18next", () => ({
  useTranslation: () => translationHook,
}));

const writeFileMock = vi.fn().mockResolvedValue("sha256-updated-digest");

vi.mock("../src/services/tauri/ide", () => ({
  ideApi: {
    readFile: vi.fn().mockResolvedValue({
      path: "docs/summary.md",
      content: "# Initial Summary\n\nGenerated by AgentZ.",
      encoding: "utf-8",
      is_binary: false,
      size: 40,
      language: "markdown",
      sha256: "sha256-initial-digest",
    }),
    writeFile: (...args: unknown[]) => writeFileMock(...args),
    gitDiff: vi.fn().mockResolvedValue({
      path: "docs/summary.md",
      original: "# Initial Summary\n\nGenerated by AgentZ.",
      modified: "# Updated Summary\n\nEdited by human in WorkZ canvas.",
      hunks: [],
    }),
  },
}));

describe("AgentZ 1.0 Golden Journey E2E Suite (R10-22)", () => {
  let root: ReactTestRenderer | null = null;

  afterEach(async () => {
    if (root) {
      await act(async () => {
        root?.unmount();
      });
      root = null;
    }
  });

  it("completes the 5-stage cross-view golden user journey end-to-end", async () => {
    // ── Stage 1: First-run 3-step Onboarding Wizard ──────────────────────
    let selectedMode: "workz" | "codez" = "workz";
    let onboardingFinished = false;

    await act(async () => {
      root = create(
        <OnboardingModal
          open={true}
          hasConfiguredModel={true}
          currentMode="workz"
          onSelectMode={(m) => {
            selectedMode = m;
          }}
          onOpenSettings={() => {}}
          onFinish={() => {
            onboardingFinished = true;
          }}
          onDismiss={() => {}}
        />,
      );
    });

    const next1 = root!.root.findByProps({ "data-testid": "onboarding-next-1" });
    await act(async () => {
      next1.props.onClick();
    });
    expect(root!.root.findByProps({ "data-testid": "onboarding-step-2" })).toBeTruthy();

    const next2 = root!.root.findByProps({ "data-testid": "onboarding-next-2" });
    await act(async () => {
      next2.props.onClick();
    });
    expect(root!.root.findByProps({ "data-testid": "onboarding-step-3" })).toBeTruthy();

    const finishBtn = root!.root.findByProps({ "data-testid": "onboarding-finish-btn" });
    await act(async () => {
      finishBtn.props.onClick();
    });
    expect(selectedMode).toBe("workz");
    expect(onboardingFinished).toBe(true);
    await act(async () => {
      root?.unmount();
      root = null;
    });

    // ── Stage 2: WorkZ Empty State Starter Scenario Selection ────────────
    let pickedScenarioId = "";
    await act(async () => {
      root = create(
        <WorkzEmptyState
          onSelectScenario={(scenario) => {
            pickedScenarioId = scenario.id;
          }}
        />,
      );
    });

    const docsCard = root!.root.findByProps({ "data-testid": "workz-starter-docs" });
    await act(async () => {
      docsCard.props.onClick();
    });
    expect(pickedScenarioId).toBe("docs");
    await act(async () => {
      root?.unmount();
      root = null;
    });

    // ── Stage 3: WorkZ Editable Preview Canvas -> Save -> Human Edit Ledger -> Continue Chat
    let handoffOpened = false;
    let continuedPayload: { path: string; content: string } | null = null;
    const projectDir = "/workspace/demo-project";

    await act(async () => {
      root = create(
        <AgentFilePreview
          projectDir={projectDir}
          path="docs/summary.md"
          artifacts={["docs/summary.md"]}
          onSelectPath={() => {}}
          onClose={() => {}}
          onOpenInCodeZ={() => {
            handoffOpened = true;
          }}
          onContinueWithEdits={(payload) => {
            continuedPayload = payload;
          }}
        />,
      );
    });

    // Wait for async readFile to settle
    await act(async () => {
      await new Promise((r) => setTimeout(r, 20));
    });

    const editTab = root!.root.findByProps({ "data-testid": "preview-mode-edit" });
    await act(async () => {
      editTab.props.onClick();
    });

    const textarea = root!.root.findByProps({ "data-testid": "preview-edit-textarea" });
    await act(async () => {
      textarea.props.onChange({
        target: { value: "# Updated Summary\n\nEdited by human in WorkZ canvas." },
      });
    });

    const saveBtn = root!.root.findByProps({ "data-testid": "preview-save-btn" });
    await act(async () => {
      await saveBtn.props.onClick();
    });

    expect(writeFileMock).toHaveBeenCalledWith(
      "/workspace/demo-project/docs/summary.md",
      "# Updated Summary\n\nEdited by human in WorkZ canvas.",
      "sha256-initial-digest",
    );

    // Verify human edit feedback ledger captured the edit and formats <user_recent_edits>
    const edits = consumeUserRecentEdits(projectDir);
    expect(edits).toHaveLength(1);
    expect(edits[0].path).toBe("docs/summary.md");
    const block = formatUserRecentEditsBlock(edits);
    expect(block).toContain("<user_recent_edits>");
    expect(block).toContain("docs/summary.md");

    const continueBtn = root!.root.findByProps({
      "data-testid": "preview-continue-with-edits",
    });
    await act(async () => {
      continueBtn.props.onClick();
    });
    expect(continuedPayload).toEqual({
      path: "docs/summary.md",
      content: "# Updated Summary\n\nEdited by human in WorkZ canvas.",
    });

    const openInCodezBtn = root!.root.findByProps({
      "data-testid": "preview-open-in-codez",
    });
    await act(async () => {
      openInCodezBtn.props.onClick();
    });
    expect(handoffOpened).toBe(true);
    await act(async () => {
      root?.unmount();
      root = null;
    });

    // ── Stage 4: CodeZ Dirty Buffer Conflict Guard (View Diff / Keep Mine / Accept Disk)
    const tracker = new EditorConflictTracker();
    tracker.setScope(projectDir);
    tracker.open("docs/summary.md", "# Updated Summary\n", false);
    tracker.edit("docs/summary.md", "# Updated Summary\nHuman unsaved local line\n");

    const bgRead = tracker.beginRead("docs/summary.md");
    expect(bgRead).toBeTruthy();
    const settlement = tracker.settleRead(bgRead!, {
      kind: "content",
      content: "# Updated Summary\nAgent modified on disk\n",
    });
    expect(settlement.status).toBe("conflict");
    expect(tracker.getConflict("docs/summary.md")).toEqual({
      path: "docs/summary.md",
      localContent: "# Updated Summary\nHuman unsaved local line\n",
      diskContent: "# Updated Summary\nAgent modified on disk\n",
    });

    const accepted = tracker.resolveConflictAcceptDisk("docs/summary.md");
    expect(accepted).toEqual({
      status: "applied",
      content: "# Updated Summary\nAgent modified on disk\n",
    });
    expect(tracker.getConflict("docs/summary.md")).toBeNull();
    expect(tracker.snapshot("docs/summary.md")?.isDirty).toBe(false);
  });
});
